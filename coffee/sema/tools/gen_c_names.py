"""Writes src/c_names.cf: the names of the bundled libc/libm functions and C type aliases.
The Rust compiler resolves these without a `use`, so the analyzer does too.

    python3 tools/gen_c_names.py
"""
import os, re

HERE = os.path.dirname(os.path.abspath(__file__))
CFC = os.path.join(HERE, '..', '..', '..', 'library', 'cfc')
funcs, types = [], []
for lib in ('libc.cfc', 'libm.cfc'):
    for line in open(os.path.join(CFC, lib), encoding='utf8'):
        m = re.match(r'c fn (\w+)\(', line)
        if m and m.group(1) not in funcs:
            funcs.append(m.group(1))
        m = re.match(r'type (\w+):', line)
        if m and m.group(1) not in types:
            types.append(m.group(1))


def wrap(words):
    lines, cur = [], ''
    for w in words:
        if len(cur) + len(w) + 1 > 96:
            lines.append(cur); cur = w
        else:
            cur = (cur + ' ' + w).strip()
    lines.append(cur)
    return lines


out = ['/#/ Generated by tools/gen_c_names.py from library/cfc/{libc,libm}.cfc. Do not edit.', '']
for name, words in (('c_function_names', funcs), ('c_type_names', types)):
    out.append('fn %s() => str:' % name)
    out.append('    let s = "%s"' % ' '.join(words[:1]))
    for chunk in wrap(words[1:]):
        out.append('    s = s + " %s"' % chunk)
    out.append('    return s')
    out.append('')
open(os.path.join(HERE, '..', 'src', 'c_names.cf'), 'w').write('\n'.join(out))
print(len(funcs), 'functions,', len(types), 'types')
