#!/bin/sh
# Regenerates ir/src/fmtrt.cf, the text of rt/src/fmt.cf as a Coffee function, from the source.
# The compiler adds that text to a program whose f-strings print an int or a float.
cd "$(dirname "$0")" || exit 1
{
    echo '/#/ GENERATED by rt/gen.sh from rt/src/fmt.cf: do not edit.'
    echo '/#/ The number-printing runtime a program gets when an f-string prints an int or a float.'
    echo 'fn fmt_rt_text() => str:'
    echo '    let out = ""'
    awk '
        /^[ ]*\/#\// { next }
        /^[ ]*$/ { next }
        {
            gsub(/\\/, "\\\\")
            gsub(/"/, "\\\"")
            printf "    out = out + \"%s\\n\"\n", $0
        }' src/fmt.cf
    echo '    return out'
} > ../ir/src/fmtrt.cf

# The C library a `--static` program gets: min.cf (what every system shares) and, per system and
# architecture, os_<system>_<arch>.cf, which has a marker line `/#/ @split`: what comes before it goes
# before the rest, the rest after it (min.cf has one too, after its state variables, where the system's first function goes) (target.cf's `min_rt_text` puts them together).
# emit <function> <file> <part>: part is all, a (before the marker) or b (after it)
emit() {
    echo "fn $1() => str:"
    echo '    let out = ""'
    awk -v part="$3" '
        /^[ ]*\/#\/ @split/ { seen = 1; next }
        /^[ ]*\/#\// { next }
        /^[ ]*$/ { next }
        part == "a" && seen { next }
        part == "b" && !seen { next }
        {
            gsub(/\\/, "\\\\")
            gsub(/"/, "\\\"")
            printf "    out = out + \"%s\\n\"\n", $0
        }' "$2"
    echo '    return out'
}
{
    echo '/#/ GENERATED by rt/gen.sh from rt/src/min.cf and rt/src/os_*.cf: do not edit.'
    echo '/#/ The C library a `--static` program gets: allocation, copying and system calls, in Coffee.'
    emit min_rt_common_a src/min.cf a
    emit min_rt_common_b src/min.cf b
    for os in linux_x86_64 linux_aarch64; do
        emit "min_rt_os_${os}_a" "src/os_$os.cf" a
        emit "min_rt_os_${os}_b" "src/os_$os.cf" b
    done
} > ../ir/src/minrt.cf
